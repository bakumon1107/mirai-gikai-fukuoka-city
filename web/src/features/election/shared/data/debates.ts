function s(
  key: Key,
  time: string,
  text: string,
  note?: string
): DebateStatement {
  return note
    ? { candidateId: IDS[key], time, text, note }
    : { candidateId: IDS[key], time, text };
}

/** ざっくりまとめ。名前は表明順にそろえて表示するので、ここでの順は問わない */
