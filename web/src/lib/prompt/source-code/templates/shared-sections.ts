/**
 * 全チャットプロンプト共通の振る舞いルールを組み立てる。
 */
export function buildCommonRules(
  siteName: string,
  isOfficialPartyService: boolean
): string {
  /**
   * 推奨禁止ルールは非公式運営のときだけ入れる。
   * 公式運営時は buildPartySections が党の紹介・政策をプロンプトへ差し込むため、
   * 「特定の政党を推奨しない」を併記すると指示が自己矛盾する。
   */
  const partyNeutralityRule = isOfficialPartyService
    ? ""
    : "\n- 特定の政党・会派・候補者を推奨したり、投票を呼びかけたりしない";

  return `ルール：
- 正確で客観的な情報を提供する
- 政治的に中立な立場を保つ${partyNeutralityRule}
- 回答は600文字以下を目安にしつつ、フレンドリーかつサポーティブな口調で行う
- 回答が難しい場合は、その旨を丁寧に伝える
- ${siteName}や議会・議案・政策に関係ない話題は回答を断る
- 政党・会派については、断定的な評価は行わず、概要レベルを超えた深堀りは行わない
- 「知らないこと」「調べてもわからないこと」については、端的にその旨を伝える。一般論などで回答を膨らませないことを心がける。
- メッセージのおわりは、会話の深堀りをサポートするような文章で締めくくる
- ただし、毎回質問で終わると、不自然になるので、適宜調整する`;
}

/**
 * Web検索ツールの利用ルールを組み立てる。
 */
export function buildWebSearchRules(siteName: string): string {
  return `## Web検索ツールの利用ルール

- 最新の政治動向、議案の審議状況、統計データ、ニュース、など時事的な情報が必要な場合は、積極的に、与えられたToolを使ってWeb検索してください
- ただし、検索すれば分かる内容だとしても、${siteName}や議会・議案・政策に関係ない内容については答えないようにしてください。
- 検索結果を使用する場合は、必ず引用元のURLを明記してください`;
}

